/** Regenerates supabase/migrations/20261111000026_exploration_tasks.sql from scripts/exploration/tasks.ts. */
import { writeFileSync } from "node:fs";
import { EXPLORATION_TASKS } from "./tasks";

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const arr = (a: string[]) => `array[${a.map(q).join(", ")}]::text[]`;
const rows = EXPLORATION_TASKS.map(
  (t) => `  (${q(t.slug)}, ${q(t.category)}, ${t.minutes}, ${q(t.title_en)}, ${q(t.title_ar)}, ${q(t.role_en)}, ${q(t.role_ar)},
   ${arr(t.daily_en)}, ${arr(t.daily_ar)}, ${q(t.scenario_en)}, ${q(t.scenario_ar)}, ${q(t.deliverable_en)}, ${q(t.deliverable_ar)},
   ${q(JSON.stringify(t.criteria))}::jsonb, ${arr(t.next_en)}, ${arr(t.next_ar)})`,
);
const sql = `-- JADARAH — 0026 exploratory tasks (generated by scripts/exploration/generate-sql.ts — do not edit by hand)
-- One short learning task per existing job category. Not employer assessments; never a hiring score. Idempotent.
insert into public.exploration_tasks (slug, category_id, minutes, title_en, title_ar, role_en, role_ar, daily_en, daily_ar,
  scenario_en, scenario_ar, deliverable_en, deliverable_ar, criteria, next_steps_en, next_steps_ar)
select v.slug, c.id, v.minutes, v.title_en, v.title_ar, v.role_en, v.role_ar, v.daily_en, v.daily_ar,
  v.scenario_en, v.scenario_ar, v.deliverable_en, v.deliverable_ar, v.criteria, v.next_en, v.next_ar
from (values
${rows.join(",\n")}
) as v (slug, category, minutes, title_en, title_ar, role_en, role_ar, daily_en, daily_ar, scenario_en, scenario_ar,
        deliverable_en, deliverable_ar, criteria, next_en, next_ar)
join public.job_categories c on c.slug = v.category
on conflict (slug) do update set category_id = excluded.category_id, minutes = excluded.minutes,
  title_en = excluded.title_en, title_ar = excluded.title_ar, role_en = excluded.role_en, role_ar = excluded.role_ar,
  daily_en = excluded.daily_en, daily_ar = excluded.daily_ar, scenario_en = excluded.scenario_en, scenario_ar = excluded.scenario_ar,
  deliverable_en = excluded.deliverable_en, deliverable_ar = excluded.deliverable_ar, criteria = excluded.criteria,
  next_steps_en = excluded.next_steps_en, next_steps_ar = excluded.next_steps_ar;
`;
writeFileSync("supabase/migrations/20261111000026_exploration_tasks.sql", sql);
console.log(`wrote ${EXPLORATION_TASKS.length} tasks`);

-- JADARAH — remove fabricated / demo / test data            (MANUAL, OWNER-APPROVED USE ONLY)
--
-- What it removes
--   1. Demo identities (profiles.is_demo) and fictional demo companies (company_profiles.is_demo), with everything
--      that cascades from them (their applications, interviews, notifications, CV records…).
--   2. "Integration Test Org …" organizations left by test runs (no real members, no real applications).
--   3. Imported practice listings: jobs with listing_type = 'simulation' and no employer author, with no application
--      from a real (non-demo) candidate. Closed "Test role …" jobs left by E2E runs fall in this group once their demo
--      author is deleted in step 1.
--
-- What it keeps (never touched)
--   Real users and their data · the registry organizations (ALM-001…010) and their identity/subscriptions ·
--   jobs posted by real employers · every assessment and assessment template (including the saved builder drafts),
--   the reference library, skills taxonomy, learning resources, exploration tasks, platform settings.
--
-- Usage
--   psql "$SUPABASE_DB_URL" -v ON_ERROR_STOP=1 -f scripts/cleanup/remove-fabricated-data.sql
--   It runs inside a transaction, prints what it would delete, and ROLLS BACK. Review the output, then change the
--   final ROLLBACK to COMMIT and run it again. Take a backup first (Dashboard → Database → Backups).
-- Storage objects of deleted demo CVs are not removed by SQL; delete the {user_id}/ folders of the listed demo users
-- in the private bucket `candidate-cvs` afterwards if wanted.

begin;

create temp table _demo_users on commit drop as select id from public.profiles where is_demo;
create temp table _demo_companies on commit drop as select id from public.company_profiles where is_demo;
create temp table _test_orgs on commit drop as
  select c.id from public.company_profiles c
  where not c.is_demo and c.registry_id is null and c.name_en like 'Integration Test Org %'
    and not exists (select 1 from public.company_memberships m join public.profiles p on p.id = m.user_id
                    where m.company_id = c.id and not p.is_demo)
    and not exists (select 1 from public.applications a join public.profiles p on p.id = a.candidate_id
                    where a.company_id = c.id and not p.is_demo);

-- ---------------------------------------------------------------- preview
select 'demo identities' as what, count(*) from _demo_users
union all select 'demo companies', count(*) from _demo_companies
union all select 'integration test organizations', count(*) from _test_orgs
union all select 'real (non-demo) users kept', count(*) from public.profiles where not is_demo
union all select 'registry organizations kept', count(*) from public.company_profiles where registry_id is not null;

-- ---------------------------------------------------------------- 1. demo identities and companies
-- Fictional companies first: their jobs, applications, evaluations and interviews cascade with them.
delete from public.company_profiles where id in (select id from _demo_companies);
-- Maintenance switch honoured by the final-evaluation guard (same one its RPCs use); scoped to this transaction.
set local jadarah.final_eval_rpc = 'on';
-- Audit columns on rows that are KEPT (e.g. builder drafts at registry organizations generated by a demo recruiter)
-- are detached from the demo author instead of blocking the delete.
update public.assessment_generations set created_by = null where created_by in (select id from _demo_users);
update public.assessment_generations set approved_by = null where approved_by in (select id from _demo_users);
update public.interview_rubrics set updated_by = null where updated_by in (select id from _demo_users);
update public.company_brand_profiles set updated_by = null where updated_by in (select id from _demo_users);
update public.company_subscriptions set activated_by = null where activated_by in (select id from _demo_users);
update public.company_payments set recorded_by = null where recorded_by in (select id from _demo_users);
update public.company_access_requests set reviewed_by = null where reviewed_by in (select id from _demo_users);
update public.final_evaluations set created_by = null where created_by in (select id from _demo_users);
update public.final_evaluations set ai_generated_by = null where ai_generated_by in (select id from _demo_users);
update public.final_evaluations set decided_by = null where decided_by in (select id from _demo_users);
update public.final_evaluations set finalized_by = null where finalized_by in (select id from _demo_users);
delete from public.final_evaluation_comments where author_id in (select id from _demo_users);
delete from auth.users where id in (select id from _demo_users);

-- ---------------------------------------------------------------- 2. integration test organizations
delete from public.company_profiles where id in (select id from _test_orgs);

-- ---------------------------------------------------------------- 3. imported practice listings
create temp table _practice_jobs on commit drop as
  select j.id, j.title_en, c.name_en as organization from public.jobs j
  join public.company_profiles c on c.id = j.company_id
  where j.listing_type = 'simulation' and j.created_by is null
    and not exists (select 1 from public.applications a join public.profiles p on p.id = a.candidate_id
                    where a.job_id = j.id and not p.is_demo);
select organization, title_en from _practice_jobs order by 1, 2;
delete from public.jobs where id in (select id from _practice_jobs);

-- ---------------------------------------------------------------- after
select 'users' as what, count(*) from public.profiles
union all select 'companies', count(*) from public.company_profiles
union all select 'published jobs', count(*) from public.jobs where status = 'published'
union all select 'applications', count(*) from public.applications
union all select 'assessments remaining', count(*) from public.assessments;

-- Change to COMMIT only after reviewing the output above.
rollback;
